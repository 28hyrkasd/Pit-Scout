-- Pit Scout: core schema.
--
-- Access model: every table has RLS enabled, and every policy grants access to
-- the `authenticated` role only. `anon` has no grants and no policies.
-- Signups are disabled in config.toml; scouts are invited from the dashboard.

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- events: cache of TBA events that have been selected in the app
-- ---------------------------------------------------------------------------

create table public.events (
  key         text primary key check (key ~ '^[0-9]{4}[a-z0-9]+$'),
  name        text not null,
  year        integer not null check (year between 1992 and 2100),
  start_date  date,
  end_date    date,
  city        text,
  state_prov  text,
  country     text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index events_year_idx on public.events (year);

create trigger events_set_updated_at
  before update on public.events
  for each row execute function public.set_updated_at();

alter table public.events enable row level security;

-- ---------------------------------------------------------------------------
-- field_definitions: customizable scouting fields (data, not code)
--
-- Fields are never hard-deleted. They are archived, so keys in
-- scouting_entries.answers never dangle.
--
-- options (dropdown):  [{ "value": "tank", "label": "Tank", "tone": "good" }]
--   tone is one of good | neutral | bad.
-- number:   higher_is_better + good_threshold + bad_threshold
--           higher_is_better = true : value >= good_threshold -> good,
--                                     value <= bad_threshold  -> bad
--           higher_is_better = false: value <= good_threshold -> good,
--                                     value >= bad_threshold  -> bad
--           anything in between is neutral (yellow).
-- yes_no:   good_answer = true  -> "yes" is good, "no" is bad
--           good_answer = false -> "no" is good, "yes" is bad
--           good_answer is null -> both answers are neutral
-- ---------------------------------------------------------------------------

create table public.field_definitions (
  id                uuid primary key default gen_random_uuid(),
  name              text not null check (char_length(btrim(name)) between 1 and 80),
  section           text not null check (section in ('specs', 'auto', 'endgame', 'other')),
  type              text not null check (type in ('number', 'yes_no', 'dropdown', 'text')),
  options           jsonb,
  higher_is_better  boolean,
  good_threshold    numeric,
  bad_threshold     numeric,
  good_answer       boolean,
  sort_order        integer not null default 0,
  archived          boolean not null default false,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),

  -- dropdown: needs a non-empty options array; every other type has none.
  constraint field_options_match_type check (
    (type = 'dropdown'
       and options is not null
       and jsonb_typeof(options) = 'array'
       and jsonb_array_length(options) > 0)
    or (type <> 'dropdown' and options is null)
  ),

  -- number-only columns must be unset for other types.
  constraint field_number_cols_match_type check (
    type = 'number'
    or (higher_is_better is null and good_threshold is null and bad_threshold is null)
  ),

  -- when both thresholds are set they must be ordered consistently with
  -- higher_is_better, so "good" and "bad" can never overlap.
  constraint field_thresholds_ordered check (
    type <> 'number'
    or good_threshold is null
    or bad_threshold is null
    or higher_is_better is null
    or (higher_is_better and good_threshold > bad_threshold)
    or (not higher_is_better and good_threshold < bad_threshold)
  ),

  -- good_answer only applies to yes_no.
  constraint field_good_answer_match_type check (
    type = 'yes_no' or good_answer is null
  )
);

create index field_definitions_active_idx
  on public.field_definitions (section, sort_order)
  where not archived;

create trigger field_definitions_set_updated_at
  before update on public.field_definitions
  for each row execute function public.set_updated_at();

alter table public.field_definitions enable row level security;

-- ---------------------------------------------------------------------------
-- scouting_entries: one per (event, team). id is generated by the client so
-- that offline creation and sync retries are idempotent.
--
-- updated_at is owned by the CLIENT (it is the last-write-wins clock), so there
-- is intentionally no set_updated_at trigger on this table.
-- ---------------------------------------------------------------------------

create table public.scouting_entries (
  id           uuid primary key,
  event_key    text not null references public.events (key) on update cascade,
  team_number  integer not null check (team_number between 1 and 99999),
  answers      jsonb not null default '{}'::jsonb check (jsonb_typeof(answers) = 'object'),
  rating       smallint check (rating between 1 and 5),
  notes        text,
  scouted_by   text check (scouted_by is null or char_length(scouted_by) <= 80),
  created_by   uuid default auth.uid() references auth.users (id) on delete set null,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),

  constraint scouting_entries_event_team_key unique (event_key, team_number)
);

create index scouting_entries_event_idx on public.scouting_entries (event_key);

alter table public.scouting_entries enable row level security;

-- ---------------------------------------------------------------------------
-- entry_photos: metadata for objects in the private "robot-photos" bucket.
-- id is client-generated. storage_path is deterministic:
--   {event_key}/{team_number}/{photo_id}.jpg
-- so a retried upload targets the same object.
-- ---------------------------------------------------------------------------

create table public.entry_photos (
  id            uuid primary key,
  entry_id      uuid not null references public.scouting_entries (id) on delete cascade,
  storage_path  text not null unique,
  created_at    timestamptz not null default now()
);

create index entry_photos_entry_idx on public.entry_photos (entry_id);

alter table public.entry_photos enable row level security;

-- ---------------------------------------------------------------------------
-- upsert_scouting_entry: last-write-wins by updated_at, keyed on
-- (event_key, team_number).
--
-- Why a function instead of a plain upsert:
--  1. A plain upsert would let a stale offline edit overwrite a newer one.
--  2. Two scouts offline can create entries for the same event+team with
--     DIFFERENT client UUIDs. The unique constraint would then reject the
--     second one forever. Here the existing row keeps its id (so any photos
--     already attached to it stay valid) and takes the newer content when the
--     incoming updated_at is later; otherwise the incoming write is dropped.
--
-- SECURITY INVOKER: runs as the caller, so RLS still applies.
-- Returns the surviving row. Its id may differ from p_id; the caller must
-- re-point any locally queued photos for that team to the returned id.
-- ---------------------------------------------------------------------------

create or replace function public.upsert_scouting_entry(
  p_id           uuid,
  p_event_key    text,
  p_team_number  integer,
  p_answers      jsonb,
  p_rating       smallint,
  p_notes        text,
  p_scouted_by   text,
  p_created_at   timestamptz,
  p_updated_at   timestamptz
)
returns public.scouting_entries
language plpgsql
security invoker
set search_path = ''
as $$
declare
  existing public.scouting_entries;
  result   public.scouting_entries;
begin
  -- Serialize concurrent writers for the same event+team.
  perform pg_advisory_xact_lock(hashtextextended(p_event_key || ':' || p_team_number::text, 0));

  select * into existing
  from public.scouting_entries
  where event_key = p_event_key and team_number = p_team_number;

  if not found then
    insert into public.scouting_entries as e
      (id, event_key, team_number, answers, rating, notes, scouted_by, created_at, updated_at)
    values
      (p_id, p_event_key, p_team_number, coalesce(p_answers, '{}'::jsonb), p_rating, p_notes,
       p_scouted_by, coalesce(p_created_at, now()), p_updated_at)
    on conflict (id) do update
      set answers = excluded.answers,
          rating = excluded.rating,
          notes = excluded.notes,
          scouted_by = excluded.scouted_by,
          updated_at = excluded.updated_at
      where e.updated_at < excluded.updated_at
    returning * into result;

    if result.id is null then
      select * into result from public.scouting_entries where id = p_id;
    end if;
    return result;
  end if;

  -- Same logical entry arriving again (retry) or an edit of it.
  if existing.id = p_id then
    if existing.updated_at < p_updated_at then
      update public.scouting_entries
         set answers = coalesce(p_answers, '{}'::jsonb),
             rating = p_rating,
             notes = p_notes,
             scouted_by = p_scouted_by,
             updated_at = p_updated_at
       where id = existing.id
       returning * into result;
      return result;
    end if;
    return existing; -- stale write: ignore, return what is stored
  end if;

  -- Different client UUID for the same event+team: later updated_at wins.
  if existing.updated_at >= p_updated_at then
    -- Existing row is newer (or equal). Keep it; incoming id is dropped.
    return existing;
  end if;

  -- Incoming is newer: overwrite the existing row's content in place. It keeps
  -- its id so photo foreign keys stay valid. The caller learns the surviving
  -- id from the returned row and re-points any local photos to it.
  update public.scouting_entries
     set answers = coalesce(p_answers, '{}'::jsonb),
         rating = p_rating,
         notes = p_notes,
         scouted_by = p_scouted_by,
         updated_at = p_updated_at
   where id = existing.id
   returning * into result;

  return result;
end;
$$;

-- ---------------------------------------------------------------------------
-- Grants: authenticated only. Nothing for anon or public.
--
-- Supabase's default privileges grant ALL on new public tables directly to
-- anon, authenticated and service_role. Revoking from anon/public alone leaves
-- authenticated with table-level DELETE/TRUNCATE etc. (RLS would still hide the
-- rows, but we want the grant layer to match intent too). So revoke from
-- authenticated as well, then re-grant exactly what we need.
-- ---------------------------------------------------------------------------

revoke all on public.events            from anon, authenticated, public;
revoke all on public.field_definitions from anon, authenticated, public;
revoke all on public.scouting_entries  from anon, authenticated, public;
revoke all on public.entry_photos      from anon, authenticated, public;
revoke all on function public.upsert_scouting_entry(uuid, text, integer, jsonb, smallint, text, text, timestamptz, timestamptz) from anon, public;
revoke all on function public.set_updated_at() from anon, public;

grant select, insert, update          on public.events            to authenticated;
grant select, insert, update          on public.field_definitions to authenticated;
grant select, insert, update          on public.scouting_entries  to authenticated;
grant select, insert, delete          on public.entry_photos      to authenticated;
grant execute on function public.upsert_scouting_entry(uuid, text, integer, jsonb, smallint, text, text, timestamptz, timestamptz) to authenticated;

-- ---------------------------------------------------------------------------
-- RLS policies (authenticated only).
--
-- Deliberately NOT granted: DELETE on events / field_definitions /
-- scouting_entries. Fields are archived, not deleted, and entries are
-- overwritten via upsert. entry_photos can be deleted (user removes a photo).
-- ---------------------------------------------------------------------------

create policy "events: read"   on public.events for select to authenticated using (true);
create policy "events: insert" on public.events for insert to authenticated with check (true);
create policy "events: update" on public.events for update to authenticated using (true) with check (true);

create policy "fields: read"   on public.field_definitions for select to authenticated using (true);
create policy "fields: insert" on public.field_definitions for insert to authenticated with check (true);
create policy "fields: update" on public.field_definitions for update to authenticated using (true) with check (true);

create policy "entries: read"   on public.scouting_entries for select to authenticated using (true);
create policy "entries: insert" on public.scouting_entries for insert to authenticated with check (true);
create policy "entries: update" on public.scouting_entries for update to authenticated using (true) with check (true);

create policy "photos: read"   on public.entry_photos for select to authenticated using (true);
create policy "photos: insert" on public.entry_photos for insert to authenticated with check (true);
create policy "photos: delete" on public.entry_photos for delete to authenticated using (true);
